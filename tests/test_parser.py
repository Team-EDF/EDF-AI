def run_tests():
    pass_count = 0
    fail_count = 0

    for case in CASES:
        result = parse_receipt_text(case["ocr"])
        errors = []

        if case.get("merchant") is not None:
            actual = result.get("merchant_name")
            if actual != case["merchant"]:
                errors.append(f"  merchant: 기대={case['merchant']!r}  실제={actual!r}")

        if case.get("total") is not None:
            actual = result.get("total_amount")
            if actual != case["total"]:
                errors.append(f"  total:    기대={case['total']}  실제={actual}")

        if case.get("item_count") is not None:
            actual = len(result.get("items", []))
            if actual != case["item_count"]:
                items_preview = [(i["name"], i["price"]) for i in result.get("items", [])]
                errors.append(f"  items:    기대={case['item_count']}개  실제={actual}개  {items_preview}")

        if errors:
            print(f"❌ {case['name']}")
            for e in errors:
                print(e)
            fail_count += 1
        else:
            print(f"✅ {case['name']}")
            pass_count += 1

    print(f"\n{'='*50}")
    print(f"결과: {pass_count}개 통과 / {fail_count}개 실패 / 총 {len(CASES)}개")

    # 전체 파싱 결과 출력 (디버깅용)
    if "--verbose" in sys.argv or "-v" in sys.argv:
        print("\n" + "="*50)
        print("상세 파싱 결과")
        print("="*50)
        for case in CASES:
            result = parse_receipt_text(case["ocr"])
            print(f"\n[{case['name']}]")
            print(f"  merchant : {result['merchant_name']}")
            print(f"  total    : {result['total_amount']}")
            print(f"  date     : {result['payment_date']}")
            items = result.get("items", [])
            if items:
                for item in items:
                    print(f"  item     : {item['name']} / {item['price']}원")
            else:
                print(f"  items    : (없음 — 가맹점 기반 분류)")


if __name__ == "__main__":
    run_tests()
