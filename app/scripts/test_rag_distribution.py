# ============================================================
# 파일명 추출
# ============================================================

def get_filename(source: str | None) -> str:
    if not source:
        return "NO_SOURCE"

    return (
        source
        .replace("\\", "/")
        .split("/")[-1]
    )


# ============================================================
# RAG 검색 분포 테스트
# ============================================================

def main():

    source_counter = Counter()
    rank1_counter = Counter()

    print("\n========================================")
    print(" RAG Search Distribution Test")
    print("========================================")

    print(f"\n총 테스트 질문 수: {len(TEST_QUERIES)}개")

    for index, query in enumerate(
        TEST_QUERIES,
        start=1,
    ):

        print("\n")
        print("=" * 70)
        print(f"[QUERY {index}] {query}")
        print("=" * 70)

        result = search_rag(
            query=query,
            k=5,
            preferred_category="food",
        )

        sources = result.get(
            "sources",
            [],
        )

        if not sources:
            print("검색 결과 없음")
            continue

        for rank, source_info in enumerate(
            sources,
            start=1,
        ):

            filename = get_filename(
                source_info.get("source")
            )

            page = source_info.get("page")

            source_counter[filename] += 1

            if rank == 1:
                rank1_counter[filename] += 1

            print(
                f"{rank}. "
                f"{filename} "
                f"(page={page})"
            )

    # ========================================================
    # 전체 검색 결과 PDF 분포
    # ========================================================

    print("\n\n")
    print("=" * 70)
    print(" 전체 검색 결과 PDF 분포")
    print("=" * 70)

    total_results = sum(
        source_counter.values()
    )

    print(f"총 검색 결과 수: {total_results}")

    for filename, count in (
        source_counter.most_common()
    ):

        percentage = (
            count / total_results * 100
            if total_results
            else 0
        )

        print(
            f"{filename}: "
            f"{count}회 "
            f"({percentage:.1f}%)"
        )

    # ========================================================
    # Rank 1 PDF 분포
    # ========================================================

    print("\n")
    print("=" * 70)
    print(" Rank 1 PDF 분포")
    print("=" * 70)

    total_rank1 = sum(
        rank1_counter.values()
    )

    print(f"총 Rank 1 결과 수: {total_rank1}")

    for filename, count in (
        rank1_counter.most_common()
    ):

        percentage = (
            count / total_rank1 * 100
            if total_rank1
            else 0
        )

        print(
            f"{filename}: "
            f"{count}회 "
            f"({percentage:.1f}%)"
        )

    # ========================================================
    # 사용된 PDF 종류
    # ========================================================

    print("\n")
    print("=" * 70)
    print(" 검색에 사용된 PDF")
    print("=" * 70)

    print(f"검색된 PDF 종류: {len(source_counter)}개")

    for index, filename in enumerate(
        source_counter.keys(),
        start=1,
    ):
        print(f"{index}. {filename}")

    print("\n========================================")
    print(" RAG Distribution Test Complete")
    print("========================================")


if __name__ == "__main__":
    main()