from google import genai

from app.services.rag_service import search_rag_context


client = genai.Client()


def generate_chat_feedback(message: str, receipt_data: dict) -> str:
    """
    사용자 질문과 소비 데이터를 기반으로 RAG 문서를 검색하고,
    검색된 근거를 우선 활용해 친환경 소비 피드백을 생성한다.
    """

    query = f"""
사용자 질문: {message}
소비 카테고리: {receipt_data.get("category")}
품목: {receipt_data.get("items")}
탄소배출량: {receipt_data.get("carbon_emission")}
""".strip()

    rag_context = search_rag_context(query)

    prompt = f"""
너는 소비 기반 탄소 발자국 플랫폼의 실시간 상담형 피드백 AI다.

[사용자 소비 데이터]
{receipt_data}

[참고 문서]
{rag_context}

[사용자 질문]
{message}

[답변 작성 원칙]
1. 사용자의 질문에 먼저 직접 답한다.
2. 참고 문서에 사용자 질문과 직접 관련된 구체적인 근거가 있다면 반드시 우선 활용한다.
3. 참고 문서에 정량적인 근거가 있다면 답변에 적극 활용한다.
   - 예: 감축률, 배출량, CO2-eq, 재사용 횟수, 비교 수치 등
   - 단, 질문과 직접 관련된 수치만 사용한다.
4. 참고 문서에 없는 탄소 절감 수치나 연구 결과를 임의로 만들지 않는다.
5. 탄소배출량, 감축 효과, 환경 효과처럼 사실 검증이 필요한 구체적인 설명은
   가능한 한 참고 문서에서 확인되는 내용에 근거하여 작성한다.
6. 참고 문서에 없는 구체적인 원인, 수치, 제도, 기업 사례 등을
   모델의 일반 지식만으로 새롭게 추가하지 않는다.
7. 참고 문서에서 직접 확인되지 않는 내용이 필요한 경우에는
   확정적인 사실처럼 단정하지 말고, 참고 문서가 지원하는 범위 안에서 답한다.
8. 서로 다른 참고 문서의 내용을 사용할 때는 자연스럽게 하나의 답변으로 종합한다.
9. "문서 1", "문서 2", "참고 문서", "RAG", "검색 결과",
   "(참고: 문서 1)" 같은 내부 시스템 표현을 사용자에게 노출하지 않는다.
10. 출처 번호나 내부 문서 번호를 본문에 붙이지 않는다.
11. 소비 데이터가 충분하지 않으면 월별·장기 소비 패턴이라고 단정하지 않는다.
    소비 데이터와 연결할 필요가 있을 때는 "현재 영수증 기준"이라고 표현한다.
12. 사용자가 실천 방법을 묻는 경우에는 참고 문서의 근거와 연결되는
    현실적인 행동을 2~3개 정도 제안한다.
13. 사용자가 효과나 이유만 묻는 경우에는 억지로 소비 내역이나 특정 품목을
    끌어오지 말고 질문 자체에 집중해서 답한다.
14. 카페 관련 질문에서는 참고 문서가 뒷받침하는 범위에서
    텀블러, 다회용컵, 일회용컵 감축 등 실제 행동을 우선 검토한다.
15. 답변은 상담하듯 자연스럽게 작성하되 너무 길게 쓰지 않는다.
16. 참고 문서에 강한 정량 근거가 있다면 일반적인 설명만 반복하지 말고
    그 근거가 사용자의 질문에 어떤 의미가 있는지 함께 설명한다.

[중요]
참고 문서에 사용자 질문에 직접 답하는 강한 근거가 존재한다면,
모델의 일반적인 설명보다 해당 근거를 우선하여 답변을 구성한다.

답변:
""".strip()

    response = client.models.generate_content(
        model="gemini-2.0-flash",
        contents=prompt,
    )

    if not response.text:
        return (
            "현재 참고 자료를 바탕으로 답변을 생성하지 못했습니다. "
            "질문을 조금 다르게 표현해 다시 시도해 주세요."
        )

    return response.text.strip()
